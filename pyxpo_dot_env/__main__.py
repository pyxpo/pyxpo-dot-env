"""`python -m pyxpo_dot_env <command>` in a pyxpo project:

    check     validate the env for a mode (exit 1 on problems), the same checks as the build
    show      list every variable, where it came from and whether it ships (build-only values are masked)
    example   print a .env.example (names and safe examples, no values); --write saves it
    init      create .env and .env.example and git-ignore .env*.local and .env.keys
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

from . import PREFIX
from .dotenv import DotenvError, dumps_value
from .guard import mask
from .loader import ENVIRONMENT

GITIGNORE = ["# pyxpo-dot-env: machine-only env files and dotenvx keys", ".env*.local", ".env.keys"]
STARTER = """\
# Values for every build mode. Commit this file only if it holds no secrets.
# PYXPO_PUBLIC_ variables ship inside the app (anyone can read them); other variables stay on the build machine.
# Put machine secrets in .env.local (git-ignored). Docs: https://github.com/pyxpo/pyxpo/tree/main/packages/env

PYXPO_PUBLIC_API_URL=http://localhost:8000
"""


def read_config(project: Path) -> Dict[str, Any]:
    path = project / "pyproject.toml"
    if not path.is_file():
        return {}
    try:
        import tomllib  # type: ignore[import-not-found]
    except ImportError:  # Python < 3.11
        import tomli as tomllib  # type: ignore[import-not-found,no-redef]
    with open(path, "rb") as f:
        data = tomllib.load(f)
    pyxpo = (data.get("tool") or {}).get("pyxpo") or {}
    return pyxpo if isinstance(pyxpo, dict) else {}


def _analyze(args: argparse.Namespace) -> Any:
    from .build import analyze
    project = Path(args.dir).resolve()
    return project, analyze(project, args.mode, read_config(project))


def cmd_check(args: argparse.Namespace) -> int:
    from .build import git_warnings, stray_env_files
    project, report = _analyze(args)
    files = ", ".join(p.name for p in report.loaded.files) or "no .env files"
    print("mode %s: %s" % (report.mode, files))
    n = len(report.public)
    verb = "would ship" if report.errors else "ships" if n == 1 else "ship"
    print("%d variable%s %s inside the app" % (n, "" if n == 1 else "s", verb))
    warnings = report.warnings + (git_warnings(project, report.loaded) if report.git_check else []) + [
        "%s is inside a bundled folder; keep .env files in the project root" % p for p in stray_env_files(project)]
    for w in warnings:
        print("warning: %s" % w)
    for e in report.errors:
        print("error: %s" % e)
    if report.errors:
        return 1
    print("ok")
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    _, report = _analyze(args)
    loaded = report.loaded
    names = sorted(set(loaded.values) | set(report.public))
    if not names:
        print("no variables (mode %s)" % report.mode)
        return 0
    width = max(len(n) for n in names)
    for name in names:
        ships = name in report.public
        value = report.public.get(name, loaded.values.get(name, ""))
        shown = repr(value) if ships else mask(str(value))
        print("%-*s  %-10s  %-18s  %s" % (width, name, "ships" if ships else "build-only",
                                         loaded.sources.get(name, ENVIRONMENT if name in loaded.values else
                                                            "schema default"), shown))
    for e in report.errors:
        print("error: %s" % e)
    return 1 if report.errors else 0


def as_text(value: Any) -> str:
    """A typed schema default written the way a .env file spells it."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ",".join(str(v) for v in value)
    if isinstance(value, dict):
        return json.dumps(value, separators=(",", ":"))
    return str(value)


def example_text(report: Any) -> str:
    lines = ["# Copy to .env (shared) or .env.local (this machine) and fill in. Generated by python -m pyxpo_dot_env."]
    names = sorted(set(report.schema) | set(report.loaded.entries))
    for name in names:
        var = report.schema.get(name)
        lines.append("")
        if var is not None and var.description:
            lines.append("# %s" % var.description)
        notes = []
        if var is not None:
            notes.append(var.type)
            if var.required is True:
                notes.append("required")
            elif var.required:
                notes.append("required in %s" % ", ".join(var.required))
            if var.choices:
                notes.append("one of: %s" % ", ".join(str(c) for c in var.choices))
        notes.append("ships in the app" if name.startswith(PREFIX) else "build-only, keep it out of git")
        lines.append("# %s" % ", ".join(notes))
        value = ""
        if var is not None and var.example is not None:
            value = var.example
        elif name.startswith(PREFIX) and var is not None and var.default is not None:
            value = as_text(var.default)
        lines.append("%s=%s" % (name, dumps_value(value)))
    return "\n".join(lines) + "\n"


def cmd_example(args: argparse.Namespace) -> int:
    project, report = _analyze(args)
    text = example_text(report)
    if args.write:
        target = report.loaded.directory / ".env.example"
        target.write_text(text, encoding="utf-8")
        print("wrote %s" % target)
    else:
        sys.stdout.write(text)
    return 0


def ensure_gitignore(directory: Path) -> List[str]:
    path = directory / ".gitignore"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    have = {line.strip() for line in text.splitlines()}
    add = [line for line in GITIGNORE if line not in have and not line.startswith("#")]
    if add:
        block = ("" if not text or text.endswith("\n") else "\n") + ("\n" if text else "") + \
            "\n".join([GITIGNORE[0]] + add) + "\n"
        path.write_text(text + block, encoding="utf-8")
    return add


def cmd_init(args: argparse.Namespace) -> int:
    directory = Path(args.dir).resolve()
    env = directory / ".env"
    if env.exists():
        print(".env already exists, left as it is")
    else:
        env.write_text(STARTER, encoding="utf-8")
        print("created .env")
    added = ensure_gitignore(directory)
    print("added %s to .gitignore" % ", ".join(added) if added else ".gitignore already ignores .env*.local")
    _, report = _analyze(args)
    example = directory / ".env.example"
    if not example.exists():
        example.write_text(example_text(report), encoding="utf-8")
        print("created .env.example")
    print("next: add \"env\" to modules in [tool.pyxpo] and read values with: from pyxpo_dot_env import env")
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    p = argparse.ArgumentParser(prog="python -m pyxpo_dot_env", description="Env files for pyxpo apps.")
    sub = p.add_subparsers(dest="command", required=True)
    for name, fn, help in (("check", cmd_check, "validate the env (exit 1 on problems)"),
                           ("show", cmd_show, "list variables and where they come from"),
                           ("example", cmd_example, "print or write .env.example"),
                           ("init", cmd_init, "create .env, .env.example and .gitignore entries")):
        s = sub.add_parser(name, help=help)
        s.add_argument("--mode", default="development", help="build mode (default: development)")
        s.add_argument("--dir", default=".", help="the pyxpo project folder (default: here)")
        if name == "example":
            s.add_argument("--write", action="store_true", help="save as .env.example")
        s.set_defaults(fn=fn)
    args = p.parse_args(argv)
    try:
        from pyxpo.module_hooks import check_mode
        check_mode(args.mode)
    except ImportError:
        pass
    except ValueError as e:
        print("error: %s" % e, file=sys.stderr)
        return 2
    try:
        return args.fn(args)
    except (DotenvError, OSError) as e:
        print("error: %s" % e, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
